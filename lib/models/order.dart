/// Order lifecycle from the SRS: Pending -> Confirmed -> Processing ->
/// Completed, with Cancelled as a side exit.
enum OrderStatus { pending, confirmed, processing, completed, cancelled }

extension OrderStatusX on OrderStatus {
  String get label {
    switch (this) {
      case OrderStatus.pending:
        return 'Pending';
      case OrderStatus.confirmed:
        return 'Confirmed';
      case OrderStatus.processing:
        return 'Processing';
      case OrderStatus.completed:
        return 'Completed';
      case OrderStatus.cancelled:
        return 'Cancelled';
    }
  }

  OrderStatus? get next {
    switch (this) {
      case OrderStatus.pending:
        return OrderStatus.confirmed;
      case OrderStatus.confirmed:
        return OrderStatus.processing;
      case OrderStatus.processing:
        return OrderStatus.completed;
      case OrderStatus.completed:
      case OrderStatus.cancelled:
        return null;
    }
  }

  bool get isFinal =>
      this == OrderStatus.completed || this == OrderStatus.cancelled;
}

/// A line of an order: a snapshot taken when the order was placed, so later
/// catalogue edits never rewrite history.
class OrderItem {
  const OrderItem({
    required this.productId,
    required this.productCode,
    required this.productName,
    required this.listUnitMinor,
    required this.unitMinor,
    required this.quantity,
    this.imagePath,
    this.category = '',
    this.unit = 'piece',
    this.colorName,
    this.size,
  });

  final String productId;
  final String productCode;
  final String productName;

  /// Catalogue price at the time of ordering.
  final int listUnitMinor;

  /// Price actually charged per unit (after product discount).
  final int unitMinor;
  final int quantity;
  final String? imagePath;
  final String category;
  final String unit;
  final String? colorName;
  final String? size;

  int get lineListTotalMinor => listUnitMinor * quantity;
  int get lineTotalMinor => unitMinor * quantity;
  bool get hadDiscount => unitMinor < listUnitMinor;

  String get variantLabel {
    final parts = <String>[
      if (colorName != null) colorName!,
      if (size != null) 'Size $size',
    ];
    return parts.join('  |  ');
  }
}

class OrderEvent {
  const OrderEvent({required this.status, required this.at});

  final OrderStatus status;
  final DateTime at;
}

/// Mirrors the `orders` collection in the SRS (userId, items[], totalPrice,
/// address, orderDate, status) plus checkout details.
///
/// Contact number, address, note, measurements, prices and voucher are all
/// **snapshots owned by the order**. Editing the customer's profile later
/// never changes them.
class AppOrder {
  const AppOrder({
    required this.id,
    required this.reference,
    required this.userId,
    required this.customerName,
    required this.contactPhone,
    required this.shippingAddress,
    this.note = '',
    this.measurements,
    required this.items,
    required this.subtotalMinor,
    required this.productDiscountMinor,
    required this.customerDiscountMinor,
    required this.voucherDiscountMinor,
    required this.deliveryMinor,
    required this.totalMinor,
    this.voucherCode,
    required this.payment,
    required this.status,
    required this.orderDate,
    required this.history,
    this.cancellation,
  });

  /// Stable identifier (a database key once a backend exists).
  final String id;

  /// Display reference. Generated by the FRONTEND MOCK; a backend issues the
  /// real one.
  final String reference;

  final String userId;
  final String customerName;
  final String contactPhone;
  final String shippingAddress;
  final String note;
  final OrderMeasurementSnapshot? measurements;
  final List<OrderItem> items;

  final int subtotalMinor;
  final int productDiscountMinor;
  final int customerDiscountMinor;
  final int voucherDiscountMinor;
  final int deliveryMinor;
  final int totalMinor;
  final String? voucherCode;

  final PaymentRecord payment;
  final OrderStatus status;
  final DateTime orderDate;
  final List<OrderEvent> history;
  final CancellationRecord? cancellation;

  int get itemCount => items.fold(0, (sum, item) => sum + item.quantity);
  PaymentMethod get paymentMethod => payment.method;
  int get totalDiscountMinor =>
      productDiscountMinor + customerDiscountMinor + voucherDiscountMinor;

  /// Customers may cancel only while the order is Pending (SRS).
  bool get customerCanCancel => status == OrderStatus.pending;

  /// Administrators may cancel Pending or Confirmed orders (SRS).
  bool get adminCanCancel =>
      status == OrderStatus.pending || status == OrderStatus.confirmed;

  /// An online order whose payment has not completed can be (re)attempted.
  bool get canPayOnline =>
      payment.method == PaymentMethod.online &&
      payment.status != PaymentStatus.successful &&
      status != OrderStatus.cancelled;

  AppOrder copyWith({
    OrderStatus? status,
    PaymentRecord? payment,
    List<OrderEvent>? history,
    CancellationRecord? cancellation,
  }) {
    return AppOrder(
      id: id,
      reference: reference,
      userId: userId,
      customerName: customerName,
      contactPhone: contactPhone,
      shippingAddress: shippingAddress,
      note: note,
      measurements: measurements,
      items: items,
      subtotalMinor: subtotalMinor,
      productDiscountMinor: productDiscountMinor,
      customerDiscountMinor: customerDiscountMinor,
      voucherDiscountMinor: voucherDiscountMinor,
      deliveryMinor: deliveryMinor,
      totalMinor: totalMinor,
      voucherCode: voucherCode,
      payment: payment ?? this.payment,
      status: status ?? this.status,
      orderDate: orderDate,
      history: history ?? this.history,
      cancellation: cancellation ?? this.cancellation,
    );
  }
}

/// Everything the client sends when placing an order. A backend must treat
/// [expectedTotalMinor] as a hint only and recompute prices itself.
class PlaceOrderRequest {
  const PlaceOrderRequest({
    required this.userId,
    required this.customerName,
    required this.items,
    required this.contactPhone,
    required this.shippingAddress,
    this.note = '',
    this.measurements,
    this.voucherCode,
    required this.paymentMethod,
    required this.expectedTotalMinor,
  });

  final String userId;
  final String customerName;

  /// Product, variant and quantity per line. Prices are NOT trusted: the
  /// repository looks them up again.
  final List<OrderLineRequest> items;
  final String contactPhone;
  final String shippingAddress;
  final String note;
  final OrderMeasurementSnapshot? measurements;
  final String? voucherCode;
  final PaymentMethod paymentMethod;
  final int expectedTotalMinor;
}

class OrderLineRequest {
  const OrderLineRequest({
    required this.productId,
    required this.quantity,
    this.colorName,
    this.size,
  });

  final String productId;
  final int quantity;
  final String? colorName;
  final String? size;
}
