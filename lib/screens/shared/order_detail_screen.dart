/// Order details. Customers can cancel while Pending (with a reason),
/// retry online payment, and review items after completion. The shop admin
/// can advance the status or cancel Pending/Confirmed orders (with a reason).
class OrderDetailScreen extends StatefulWidget {
  const OrderDetailScreen({super.key, required this.orderId, this.adminView = false});

  final String orderId;
  final bool adminView;

  @override
  State<OrderDetailScreen> createState() => _OrderDetailScreenState();
}

class _OrderDetailScreenState extends State<OrderDetailScreen> {
  bool _busy = false;

  Future<void> _advance(AppOrder order, OrderStatus next) async {
    final provider = context.read<OrdersProvider>();
    setState(() => _busy = true);
    try {
      await provider.updateStatus(order.id, next);
      if (mounted) {
        showAppSnack(context, 'Order marked as ${next.label}. Customer notified.');
      }
    } catch (e) {
      if (mounted) showAppSnack(context, errorText(e), error: true);
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  Future<void> _cancel(AppOrder order) async {
    final done = await showCancelOrderSheet(context, order: order, byAdmin: widget.adminView);
    if (done && mounted) showAppSnack(context, 'Order cancelled');
  }

  @override
  Widget build(BuildContext context) {
    final order = context.watch<OrdersProvider>().byId(widget.orderId);
    if (order == null) {
      return Scaffold(
        appBar: AppBar(title: const Text('Order')),
        body: const EmptyState(
          icon: Icons.search_off,
          title: 'Order not found',
          message: 'This order is no longer available.',
        ),
      );
    }

    final textTheme = Theme.of(context).textTheme;
    final next = order.status.next;
    final canCancel = widget.adminView ? order.adminCanCancel : order.customerCanCancel;
    final feedback = context.watch<FeedbackProvider>();

    return Scaffold(
      appBar: AppBar(title: const Text('Order details')),
      body: SafeArea(
        child: ListView(
          padding: const EdgeInsets.all(16),
          children: [
            // ------------------------------------------------------- header
            Card(
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text('Order reference (demo)',
                        style: textTheme.bodySmall?.copyWith(color: AppColors.muted)),
                    Text(order.reference,
                        style: textTheme.titleLarge?.copyWith(
                            fontWeight: FontWeight.w800, letterSpacing: 0.4)),
                    Text(
                      'ID ${order.id}  |  reference generated by the app, not a server order number',
                      style: textTheme.bodySmall?.copyWith(color: AppColors.muted),
                    ),
                    const SizedBox(height: 12),
                    Wrap(
                      spacing: 8,
                      runSpacing: 6,
                      crossAxisAlignment: WrapCrossAlignment.center,
                      children: [
                        Text('Order:', style: textTheme.bodyMedium),
                        StatusChip(status: order.status),
                        Text('Payment:', style: textTheme.bodyMedium),
                        PaymentChip(payment: order.payment),
                      ],
                    ),
                    const SizedBox(height: 8),
                    Text('Placed ${formatDateTime(order.orderDate)}',
                        style: textTheme.bodySmall?.copyWith(color: AppColors.muted)),
                  ],
                ),
              ),
            ),
            const SizedBox(height: 12),

            // ---------------------------------------------- cancellation
            if (order.cancellation != null) ...[
              _CancellationCard(record: order.cancellation!),
              const SizedBox(height: 12),
            ],

            // ------------------------------------------------- timeline
            Card(
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text('Order status history',
                        style: textTheme.titleSmall?.copyWith(fontWeight: FontWeight.w800)),
                    const SizedBox(height: 4),
                    Text(
                      'Updates come from the shop (demonstration data, not live tracking).',
                      style: textTheme.bodySmall?.copyWith(color: AppColors.muted),
                    ),
                    const SizedBox(height: 12),
                    _StatusTimeline(order: order),
                  ],
                ),
              ),
            ),
            const SizedBox(height: 12),

            // ------------------------------------------------------ items
            Card(
              child: Padding(
                padding: const EdgeInsets.all(16),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text('Items',
                        style: textTheme.titleSmall?.copyWith(fontWeight: FontWeight.w800)),
                    const SizedBox(height: 12),
                    for (final item in order.items) ...[
                      Row(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Container(
                            height: 48,
                            width: 48,
                            decoration: BoxDecoration(
                              color: categoryColor(item.category),
                              borderRadius: BorderRadius.circular(10),
                            ),
                            child: Icon(categoryIcon(item.category),
                                color: AppColors.burgundy, size: 22),
                          ),
                          const SizedBox(width: 12),
                          Expanded(
                            child: Column(
                              crossAxisAlignment: CrossAxisAlignment.start,
                              children: [
                                Text(item.productName,
                                    maxLines: 2, overflow: TextOverflow.ellipsis),
                                Text(
                                  'Code ${item.productCode}'
                                  '${item.variantLabel.isEmpty ? '' : '  |  ${item.variantLabel}'}',
                                  style: textTheme.bodySmall?.copyWith(color: AppColors.muted),
                                ),
                                Wrap(
                                  spacing: 6,
                                  children: [
                                    Text(
                                      '${formatMoney(item.unitMinor)} x ${item.quantity}',
                                      style: textTheme.bodySmall,
                                    ),
                                    if (item.hadDiscount)
                                      Text(
                                        formatMoney(item.listUnitMinor),
                                        style: textTheme.bodySmall?.copyWith(
                                          color: AppColors.muted,
                                          decoration: TextDecoration.lineThrough,
                                        ),
                                      ),
                                  ],
                                ),
                              ],
                            ),
                          ),
                          const SizedBox(width: 8),
                          Text(formatMoney(item.lineTotalMinor),
                              style: const TextStyle(fontWeight: FontWeight.w800)),
                        ],
                      ),
                      if (!widget.adminView && order.status == OrderStatus.completed)
                        _FeedbackRow(order: order, item: item, feedback: feedback),
                      const SizedBox(height: 12),
                    ],
                  ],
                ),
              ),
            ),
            const SizedBox(height: 12),
            PriceBreakdownCard(breakdown: breakdownOfOrder(order), totalLabel: 'Total'),
            const SizedBox(height: 12),

            // --------------------------------------- contact, payment
            Card(
              child: Padding(
                padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
                child: Column(
                  children: [
                    if (widget.adminView) ...[
                      InfoRow(
                        icon: Icons.person_outline,
                        label: 'Customer',
                        value: order.customerName,
                      ),
                      const Divider(),
                    ],
                    InfoRow(
                      icon: Icons.phone_outlined,
                      label: 'Contact number for this order',
                      value: order.contactPhone,
                    ),
                    const Divider(),
                    InfoRow(
                      icon: Icons.location_on_outlined,
                      label: 'Delivery address',
                      value: order.shippingAddress,
                    ),
                    if (order.note.isNotEmpty) ...[
                      const Divider(),
                      InfoRow(icon: Icons.edit_note, label: 'Order note', value: order.note),
                    ],
                    const Divider(),
                    InfoRow(
                      icon: Icons.payments_outlined,
                      label: 'Payment method',
                      value: order.payment.method.label,
                    ),
                    if (order.payment.isDemo)
                      Padding(
                        padding: const EdgeInsets.only(bottom: 8),
                        child: Text(
                          'Online payment status for this order comes from the demonstration flow, not a real gateway.',
                          style: textTheme.bodySmall?.copyWith(color: AppColors.warning),
                        ),
                      ),
                    if (order.voucherCode != null) ...[
                      const Divider(),
                      InfoRow(
                        icon: Icons.local_offer_outlined,
                        label: 'Voucher used',
                        value: order.voucherCode!,
                      ),
                    ],
                  ],
                ),
              ),
            ),

            // ---------------------------------------------- measurements
            if (order.measurements != null) ...[
              const SizedBox(height: 12),
              Card(
                child: Padding(
                  padding: const EdgeInsets.all(16),
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text('Measurements for this order',
                          style: textTheme.titleSmall?.copyWith(fontWeight: FontWeight.w800)),
                      const SizedBox(height: 4),
                      Text(
                        order.measurements!.source == MeasurementSource.otherPerson
                            ? '${order.measurements!.source.label}: ${order.measurements!.forPerson ?? ''}'
                            : order.measurements!.source.label,
                        style: textTheme.bodySmall,
                      ),
                      Text(
                        'Recorded ${formatDateTime(order.measurements!.capturedAt)}. A snapshot: later profile changes do not alter it.',
                        style: textTheme.bodySmall?.copyWith(color: AppColors.muted),
                      ),
                      const SizedBox(height: 10),
                      MeasurementSummary(measurements: order.measurements!.measurements),
                    ],
                  ),
                ),
              ),
            ],

            // ------------------------------------------------------ actions
            const SizedBox(height: 20),
            if (!widget.adminView && order.canPayOnline)
              Padding(
                padding: const EdgeInsets.only(bottom: 12),
                child: PrimaryButton(
                  label: order.payment.status == PaymentStatus.pending
                      ? 'Complete payment (demo)'
                      : 'Retry payment (demo)',
                  icon: Icons.credit_card,
                  onPressed: () => Navigator.of(context).push(
                    MaterialPageRoute<void>(
                      builder: (_) => PaymentDemoScreen(orderId: order.id),
                    ),
                  ),
                ),
              ),
            if (widget.adminView && next != null)
              PrimaryButton(
                label: 'Mark as ${next.label}',
                icon: Icons.check_circle_outline,
                busy: _busy,
                onPressed: () => _advance(order, next),
              ),
            if (canCancel) ...[
              const SizedBox(height: 12),
              OutlinedButton.icon(
                style: OutlinedButton.styleFrom(
                  foregroundColor: AppColors.danger,
                  side: const BorderSide(color: AppColors.danger),
                ),
                onPressed: _busy ? null : () => _cancel(order),
                icon: const Icon(Icons.cancel_outlined),
                label: const Text('Cancel Order'),
              ),
            ],
            if (!widget.adminView && order.status == OrderStatus.confirmed)
              Padding(
                padding: const EdgeInsets.only(top: 8),
                child: Text(
                  'This order has been confirmed and can no longer be cancelled by you. Please contact the shop if you need help.',
                  textAlign: TextAlign.center,
                  style: textTheme.bodySmall?.copyWith(color: AppColors.muted),
                ),
              ),
          ],
        ),
      ),
    );
  }
}

class _CancellationCard extends StatelessWidget {
  const _CancellationCard({required this.record});

  final CancellationRecord record;

  @override
  Widget build(BuildContext context) {
    final textTheme = Theme.of(context).textTheme;
    return Card(
      color: AppColors.danger.withValues(alpha: 0.05),
      child: Padding(
        padding: const EdgeInsets.all(16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                const Icon(Icons.cancel_outlined, color: AppColors.danger),
                const SizedBox(width: 8),
                Text('Order cancelled',
                    style: textTheme.titleSmall?.copyWith(
                        fontWeight: FontWeight.w800, color: AppColors.danger)),
              ],
            ),
            const SizedBox(height: 10),
            InfoRow(
              icon: Icons.person_outline,
              label: 'Cancelled by',
              value: '${record.cancelledBy.label} (${record.cancelledByName})',
            ),
            InfoRow(icon: Icons.help_outline, label: 'Reason', value: record.reason),
            if (record.note.isNotEmpty)
              InfoRow(icon: Icons.notes, label: 'Notes', value: record.note),
            InfoRow(
              icon: Icons.schedule,
              label: 'Cancelled on',
              value: formatDateTime(record.cancelledAt),
            ),
          ],
        ),
      ),
    );
  }
}

class _FeedbackRow extends StatelessWidget {
  const _FeedbackRow({required this.order, required this.item, required this.feedback});

  final AppOrder order;
  final OrderItem item;
  final FeedbackProvider feedback;

  @override
  Widget build(BuildContext context) {
    final existing = feedback.feedbackFor(order.id, item.productId);
    final textTheme = Theme.of(context).textTheme;
    return Padding(
      padding: const EdgeInsets.only(top: 8, left: 60),
      child: existing != null
          ? Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  children: [
                    StarRating(rating: existing.rating.toDouble(), size: 16),
                    const SizedBox(width: 8),
                    Text('Your feedback', style: textTheme.bodySmall),
                  ],
                ),
                Text(existing.comment, style: textTheme.bodySmall),
              ],
            )
          : Align(
              alignment: Alignment.centerLeft,
              child: OutlinedButton.icon(
                style: OutlinedButton.styleFrom(
                  minimumSize: const Size(0, 40),
                  textStyle: const TextStyle(fontSize: 13, fontWeight: FontWeight.w600),
                ),
                onPressed: () => showFeedbackSheet(context, order: order, item: item),
                icon: const Icon(Icons.rate_review_outlined, size: 18),
                label: const Text('Give feedback'),
              ),
            ),
    );
  }
}

/// Status history using the real timestamps stored on the order.
class _StatusTimeline extends StatelessWidget {
  const _StatusTimeline({required this.order});

  final AppOrder order;

  @override
  Widget build(BuildContext context) {
    final events = order.history;
    final upcoming = <OrderStatus>[];
    if (order.status != OrderStatus.cancelled) {
      var s = order.status.next;
      while (s != null) {
        upcoming.add(s);
        s = s.next;
      }
    }
    final total = events.length + upcoming.length;
    return Column(
      children: [
        for (var i = 0; i < events.length; i++)
          _TimelineStep(
            label: events[i].status.label,
            time: formatDateTime(events[i].at),
            done: true,
            danger: events[i].status == OrderStatus.cancelled,
            current: i == events.length - 1,
            isLast: i == total - 1,
          ),
        for (var i = 0; i < upcoming.length; i++)
          _TimelineStep(
            label: upcoming[i].label,
            time: null,
            done: false,
            danger: false,
            current: false,
            isLast: events.length + i == total - 1,
          ),
      ],
    );
  }
}

class _TimelineStep extends StatelessWidget {
  const _TimelineStep({
    required this.label,
    required this.time,
    required this.done,
    required this.danger,
    required this.current,
    required this.isLast,
  });

  final String label;
  final String? time;
  final bool done;
  final bool danger;
  final bool current;
  final bool isLast;

  @override
  Widget build(BuildContext context) {
    final color = danger
        ? AppColors.danger
        : (done ? AppColors.burgundy : AppColors.border);
    return IntrinsicHeight(
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          SizedBox(
            width: 28,
            child: Column(
              children: [
                Container(
                  height: 22,
                  width: 22,
                  decoration: BoxDecoration(
                    shape: BoxShape.circle,
                    color: done ? color : Colors.white,
                    border: Border.all(color: color, width: 2),
                  ),
                  child: done
                      ? Icon(danger ? Icons.close : Icons.check, size: 14, color: Colors.white)
                      : null,
                ),
                if (!isLast) Expanded(child: Container(width: 2, color: color)),
              ],
            ),
          ),
          const SizedBox(width: 12),
          Expanded(
            child: Padding(
              padding: EdgeInsets.only(bottom: isLast ? 0 : 16),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    label,
                    style: TextStyle(
                      fontWeight: current ? FontWeight.w800 : FontWeight.w500,
                      color: done ? AppColors.ink : AppColors.muted,
                    ),
                  ),
                  if (time != null)
                    Text(time!,
                        style: Theme.of(context)
                            .textTheme
                            .bodySmall
                            ?.copyWith(color: AppColors.muted)),
                ],
              ),
            ),
          ),
        ],
      ),
    );
  }
}
