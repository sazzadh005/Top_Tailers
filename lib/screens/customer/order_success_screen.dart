import 'package:provider/provider.dart';

import '../../core/format.dart';
import '../../core/theme.dart';
import '../../models/order.dart';
import '../../models/payment.dart';
import '../../providers/orders_provider.dart';
import '../../widgets/common.dart';
import '../../widgets/price_breakdown_card.dart';
import '../shared/order_detail_screen.dart';
import 'payment_demo_screen.dart';

/// Confirmation shown after an order is placed. "Order placed" and "payment
/// completed" are different facts, so the screen reports them separately.
class OrderSuccessScreen extends StatelessWidget {
  const OrderSuccessScreen({super.key, required this.orderId});

  final String orderId;

  String _paymentMessage(AppOrder order) {
    final p = order.payment;
    if (p.method == PaymentMethod.cod) {
      return 'Payment: Cash on Delivery. You pay when the order is delivered.';
    }
    switch (p.status) {
      case PaymentStatus.successful:
        return p.isDemo
            ? 'A demonstration payment was recorded. No real money was moved.'
            : 'Your online payment was confirmed.';
      case PaymentStatus.failed:
        return 'The payment attempt failed. Your order is saved; you can retry from here or from the order page.';
      case PaymentStatus.cancelled:
        return 'The payment was cancelled. Your order is saved; you can complete payment later.';
      case PaymentStatus.pending:
        return 'Online payment is not completed yet. Your order is saved and waiting for payment.';
    }
  }

  @override
  Widget build(BuildContext context) {
    final order = context.watch<OrdersProvider>().byId(orderId);
    final textTheme = Theme.of(context).textTheme;

    if (order == null) {
      return Scaffold(
        appBar: AppBar(title: const Text('Order')),
        body: const EmptyState(
          icon: Icons.search_off,
          title: 'Order not found',
          message: 'You can find your orders in the Orders tab.',
        ),
      );
    }

    return Scaffold(
      body: SafeArea(
        child: Center(
          child: SingleChildScrollView(
            padding: const EdgeInsets.all(24),
            child: ConstrainedBox(
              constraints: const BoxConstraints(maxWidth: 480),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.stretch,
                children: [
                  const Icon(Icons.check_circle, size: 88, color: AppColors.success),
                  const SizedBox(height: 12),
                  Text(
                    'Order placed',
                    textAlign: TextAlign.center,
                    style: textTheme.headlineSmall?.copyWith(fontWeight: FontWeight.w800),
                  ),
                  const SizedBox(height: 6),
                  Text(
                    _paymentMessage(order),
                    textAlign: TextAlign.center,
                    style: textTheme.bodyMedium?.copyWith(color: AppColors.muted),
                  ),
                  const SizedBox(height: 20),
                  Card(
                    child: Padding(
                      padding: const EdgeInsets.all(16),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          Text('Order reference (demo)',
                              style: textTheme.bodySmall?.copyWith(color: AppColors.muted)),
                          Text(order.reference,
                              style: textTheme.titleMedium?.copyWith(
                                  fontWeight: FontWeight.w800, letterSpacing: 0.5)),
                          Text(
                            'Generated by the app for this demonstration. A server will issue the real order number.',
                            style: textTheme.bodySmall?.copyWith(color: AppColors.muted),
                          ),
                          const Divider(height: 24),
                          Row(
                            children: [
                              const Expanded(child: Text('Order status')),
                              StatusChip(status: order.status),
                            ],
                          ),
                          const SizedBox(height: 8),
                          Row(
                            children: [
                              const Expanded(child: Text('Payment status')),
                              PaymentChip(payment: order.payment),
                            ],
                          ),
                          const SizedBox(height: 8),
                          InfoRow(
                            icon: Icons.payments_outlined,
                            label: 'Payment method',
                            value: order.payment.method.label,
                          ),
                          InfoRow(
                            icon: Icons.phone_outlined,
                            label: 'Contact number for this order',
                            value: order.contactPhone,
                          ),
                          InfoRow(
                            icon: Icons.event_outlined,
                            label: 'Placed',
                            value: formatDateTime(order.orderDate),
                          ),
                        ],
                      ),
                    ),
                  ),
                  const SizedBox(height: 12),
                  PriceBreakdownCard(breakdown: breakdownOfOrder(order)),
                  const SizedBox(height: 20),
                  if (order.canPayOnline) ...[
                    PrimaryButton(
                      label: order.payment.status == PaymentStatus.pending
                          ? 'Complete payment (demo)'
                          : 'Retry payment (demo)',
                      icon: Icons.credit_card,
                      onPressed: () => Navigator.of(context).pushReplacement(
                        MaterialPageRoute<void>(
                          builder: (_) => PaymentDemoScreen(orderId: order.id),
                        ),
                      ),
                    ),
                    const SizedBox(height: 12),
                  ],
                  ElevatedButton(
                    onPressed: () => Navigator.of(context).pushReplacement(
                      MaterialPageRoute<void>(
                        builder: (_) => OrderDetailScreen(orderId: order.id),
                      ),
                    ),
                    child: const Text('View Order'),
                  ),
                  const SizedBox(height: 12),
                  OutlinedButton(
                    onPressed: () =>
                        Navigator.of(context).popUntil((route) => route.isFirst),
                    child: const Text('Continue Shopping'),
                  ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }
}
