/// DEMONSTRATION payment step. It exists so the order -> payment flow can be
/// designed and tested before SSLCommerz is connected.
///
/// Nothing here contacts a payment provider or collects card/wallet details.
/// The three buttons simulate outcomes a gateway might report; a real
/// integration must obtain the outcome from the backend after it has verified
/// the provider's callback, never from a button in the app.
class PaymentDemoScreen extends StatefulWidget {
  const PaymentDemoScreen({super.key, required this.orderId});

  final String orderId;

  @override
  State<PaymentDemoScreen> createState() => _PaymentDemoScreenState();
}

class _PaymentDemoScreenState extends State<PaymentDemoScreen> {
  PaymentSession? _session;
  String? _error;
  bool _starting = true;
  bool _busy = false;

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addPostFrameCallback((_) => _start());
  }

  Future<void> _start() async {
    final orders = context.read<OrdersProvider>();
    final order = orders.byId(widget.orderId);
    if (order == null) {
      setState(() {
        _starting = false;
        _error = 'Order not found.';
      });
      return;
    }
    setState(() {
      _starting = true;
      _error = null;
    });
    try {
      final session = await orders.startOnlinePayment(order);
      if (mounted) setState(() => _session = session);
    } catch (e) {
      if (mounted) setState(() => _error = errorText(e));
    } finally {
      if (mounted) setState(() => _starting = false);
    }
  }

  Future<void> _finish(PaymentStatus status) async {
    final orders = context.read<OrdersProvider>();
    final navigator = Navigator.of(context);
    setState(() => _busy = true);
    try {
      await orders.recordPayment(widget.orderId, status);
      navigator.pushReplacement(
        MaterialPageRoute<void>(
          builder: (_) => OrderSuccessScreen(orderId: widget.orderId),
        ),
      );
    } catch (e) {
      if (mounted) {
        showAppSnack(context, errorText(e), error: true);
        setState(() => _busy = false);
      }
    }
  }

  void _payLater() {
    Navigator.of(context).pushReplacement(
      MaterialPageRoute<void>(
        builder: (_) => OrderSuccessScreen(orderId: widget.orderId),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final orders = context.watch<OrdersProvider>();
    final order = orders.byId(widget.orderId);
    final textTheme = Theme.of(context).textTheme;

    Widget body;
    if (_starting) {
      body = const Center(child: CircularProgressIndicator());
    } else if (_error != null || order == null) {
      body = ErrorState(message: _error ?? 'Order not found.', onRetry: _start);
    } else if (!orders.isDemoGateway) {
      body = const EmptyState(
        icon: Icons.construction,
        title: 'Gateway redirect not built yet',
        message:
            'A live gateway is configured, but redirecting to its payment page is not implemented in this build.',
      );
    } else {
      body = ListView(
        padding: const EdgeInsets.all(16),
        children: [
          const DemoNotice(
            message:
                'DEMONSTRATION ONLY. No real payment is made and no card or wallet details are collected. The buttons below only simulate outcomes so the flow can be tested. Real online payment will use SSLCommerz through the backend.',
          ),
          const SizedBox(height: 16),
          Card(
            child: Padding(
              padding: const EdgeInsets.all(16),
              child: Column(
                children: [
                  Text('Amount to pay', style: textTheme.bodySmall?.copyWith(color: AppColors.muted)),
                  const SizedBox(height: 4),
                  Text(
                    formatMoney(order.totalMinor),
                    style: textTheme.headlineMedium?.copyWith(
                        fontWeight: FontWeight.w800, color: AppColors.burgundy),
                  ),
                  const SizedBox(height: 12),
                  InfoRow(
                    icon: Icons.receipt_long_outlined,
                    label: 'Order reference (demo, generated by the app)',
                    value: order.reference,
                  ),
                  InfoRow(
                    icon: Icons.account_balance_outlined,
                    label: 'Gateway',
                    value: orders.gatewayName,
                  ),
                  if (_session != null)
                    InfoRow(
                      icon: Icons.tag,
                      label: 'Demo session',
                      value: _session!.id,
                    ),
                  Row(
                    children: [
                      Text('Payment status: ', style: textTheme.bodyMedium),
                      PaymentChip(payment: order.payment),
                    ],
                  ),
                ],
              ),
            ),
          ),
          const SizedBox(height: 20),
          Text('Simulate the gateway result',
              style: textTheme.titleSmall?.copyWith(fontWeight: FontWeight.w800)),
          const SizedBox(height: 12),
          PrimaryButton(
            label: 'Simulate: payment completed',
            icon: Icons.check_circle_outline,
            busy: _busy,
            onPressed: () => _finish(PaymentStatus.successful),
          ),
          const SizedBox(height: 10),
          OutlinedButton.icon(
            style: OutlinedButton.styleFrom(
              foregroundColor: AppColors.danger,
              side: const BorderSide(color: AppColors.danger),
            ),
            onPressed: _busy ? null : () => _finish(PaymentStatus.failed),
            icon: const Icon(Icons.error_outline),
            label: const Text('Simulate: payment failed'),
          ),
          const SizedBox(height: 10),
          OutlinedButton.icon(
            onPressed: _busy ? null : () => _finish(PaymentStatus.cancelled),
            icon: const Icon(Icons.close),
            label: const Text('Simulate: customer cancelled payment'),
          ),
          const SizedBox(height: 16),
          TextButton(
            onPressed: _busy ? null : _payLater,
            child: const Text('Pay later (order stays placed, payment pending)'),
          ),
        ],
      );
    }

    return Scaffold(
      appBar: AppBar(title: const Text('Online payment (demo)')),
      body: body,
    );
  }
}
